# Generate lean/lake_packages.bzl from lean/lake-manifest.json.
#
# Invoked by build/scripts/lean_lock.sh; kept as its own file because the
# generated content is itself full of quotes and heredoc-hostile text.

import json
import sys

HEADER = '''"""Generated by build/scripts/lean_lock.sh -- do not hand-edit.

The Lake packages resolved into @lake_deps, mirroring lean/lake-manifest.json.

This list is generated LOCALLY rather than loaded from `@lake_deps//:packages.bzl`
on purpose. A `load()` from an external repo forces that repo to be FETCHED before
the loading package can be evaluated, and `bazel build //...` evaluates every
package -- so loading the list from @lake_deps made a full Lake/Mathlib fetch the
price of building any target in the workspace, including pure-Rust ones and
including invocations that explicitly exclude //lean/....

As plain label strings the deps stay lazy: Bazel resolves them only for targets it
actually analyzes, so @lake_deps is fetched when, and only when, a //lean target is
being built.

Regenerate with `build/scripts/lean_lock.sh packages` after changing
lean/lake-manifest.json. The names must match Lake's package directory names,
which are the manifest's `name` fields.
"""

LAKE_PACKAGES = [
'''


def main() -> int:
    manifest_path, out_path = sys.argv[1], sys.argv[2]
    names = [p["name"] for p in json.load(open(manifest_path))["packages"]]

    with open(out_path, "w") as f:
        f.write(HEADER)
        for name in names:
            f.write('    "@lake_deps//:%s",\n' % name)
        f.write("]\n")

    print("lean_lock: wrote %s (%d packages)" % (out_path, len(names)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
