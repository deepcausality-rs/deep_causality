/// Unwraps an expected `Ok`, reporting the typed error rather than requiring `Debug` on `T`.
fn expect_ok<T>(result: Result<(T, usize), StatsError>, what: &str) -> (T, usize) {
    match result {
        Ok(pair) => pair,
        Err(StatsError(e)) => panic!("{what}: expected Ok, got Err({e:?})"),
    }
}

/// Asserts `|actual - expected| <= tol`, printing both through `ToPrimitive` so the message works
/// at every precision. A `NaN` actual fails, because `NaN <= tol` is false.
fn assert_close<T>(actual: T, expected: T, tol: f64, what: &str)
where
    T: RealField + FromPrimitive,
{
    let diff = (actual - expected).abs();
    assert!(
        diff <= lift::<T>(tol),
        "{what}: got {}, expected {}, tolerance {tol}",
        actual.to_f64().unwrap_or(f64::NAN),
        expected.to_f64().unwrap_or(f64::NAN)
    );
}

/// A deterministic pseudo-random family from a linear congruential recurrence.
///
/// The recurrence is integer arithmetic on `u64` with the multiplier and increment of Knuth's
/// MMIX generator. It shares no expression with the correlation code, and nothing here is
/// asserted against a value it produces — only against bounds and symmetries.
///
/// The mapping to `f64` takes 24 bits and divides by `2^23`, so every sample is an exact binary
/// fraction in `[-1, 1)` and lifts losslessly into `f32`, `f64` and `Float106` alike.
fn lcg_family(seed: u64, len: usize) -> Vec<f64> {
    let mut state = seed;
    (0..len)
        .map(|_| {
            state = state
                .wrapping_mul(6_364_136_223_846_793_005)
                .wrapping_add(1_442_695_040_888_963_407);
            let bits = (state >> 40) as f64; // 24 bits: 0 ..= 16_777_215
            bits / 8_388_608.0 - 1.0
        })
        .collect()
}

/// Wraps every element as `Some`, for the pairwise-complete fixtures.
fn all_present<T: Copy>(xs: &[T]) -> Vec<Option<T>> {
    xs.iter().map(|&v| Some(v)).collect()
}

/// `a * x + b`, elementwise, built in the working scalar.
fn affine<T>(xs: &[T], a: f64, b: f64) -> Vec<T>
where
    T: RealField + FromPrimitive,
{
    let a = lift::<T>(a);
    let b = lift::<T>(b);
    xs.iter().map(|&x| a * x + b).collect()
}

/// `x + x`, elementwise. Doubling is exact in binary floating point at every precision, so the
/// result is a perfect affine image of `xs` with no rounding anywhere in the construction.
fn doubled<T>(xs: &[T]) -> Vec<T>
where
    T: RealField + FromPrimitive,
{
    xs.iter().map(|&x| x + x).collect()
}

