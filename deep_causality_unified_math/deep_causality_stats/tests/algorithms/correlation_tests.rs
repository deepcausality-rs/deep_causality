/// Agreement with dense evaluation: deletion followed by correlation equals correlation of the
/// pairs that survive deletion, filtered here by hand rather than by the function.
///
/// This is the one test that puts a function under test on both sides, and it is required by the
/// task. It answers a different question from the test above — "does deletion change the answer"
/// rather than "is the answer right" — so the hand-computed 0.8 is asserted here as well, and it
/// is what pins the pair to the mathematics if both functions were wrong together.
fn check_pairwise_matches_dense<T>(tol: f64)
where
    T: RealField + FromPrimitive,
{
    let sparse_x: Vec<Option<T>> = vec![
        Some(lift::<T>(1.0)),
        None,
        Some(lift::<T>(2.0)),
        Some(lift::<T>(3.0)),
        Some(lift::<T>(4.0)),
        Some(lift::<T>(9.0)),
    ];
    let sparse_y: Vec<Option<T>> = vec![
        Some(lift::<T>(1.0)),
        Some(lift::<T>(7.0)),
        Some(lift::<T>(3.0)),
        Some(lift::<T>(2.0)),
        Some(lift::<T>(4.0)),
        None,
    ];

    // Filtered by hand, by reading the table above: rows 0, 2, 3 and 4.
    let dense_x = lift_array::<T>(&[1.0, 2.0, 3.0, 4.0]);
    let dense_y = lift_array::<T>(&[1.0, 3.0, 2.0, 4.0]);

    let (sparse_r, sparse_n) = expect_ok(pearson_pairwise_complete(&sparse_x, &sparse_y), "sparse");
    let (dense_r, dense_n) = expect_ok(pearson(&dense_x, &dense_y), "dense");

    assert_close(
        sparse_r,
        dense_r,
        tol,
        "pairwise-complete against dense pearson",
    );
    assert_eq!(
        sparse_n, dense_n,
        "the surviving-pair count must equal the dense sample length"
    );
    // 0.8: 4/5, from the working in check_hand_computed_small_sample.
    assert_close(
        sparse_r,
        lift::<T>(0.8),
        tol,
        "the agreed value is the hand-computed one",
    );
}

