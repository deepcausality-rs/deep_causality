//! Phase 2 suite for [`pearson`] and [`pearson_pairwise_complete`].
//!
//! # Where the expected values come from
//!
//! Every expected `r` in this file is one of:
//!
//! * a closed form evaluated by hand, with the deviations, their sums of squares and their cross
//!   product written out in the test's comment so the arithmetic can be checked without running
//!   anything;
//! * an algebraic invariant of the coefficient — symmetry in its two arguments, invariance under a
//!   positive affine map, a sign flip under a negative one, the `[-1, 1]` bound;
//! * a property over a family generated by a linear congruential recurrence, which shares no
//!   expression with the correlation code.
//!
//! No expected value is produced by calling either function under test, and no test retypes the
//! correlation formula in an assertion. The one place a function under test appears on both sides
//! is `test_pairwise_complete_matches_pearson_over_the_filtered_pairs`, which the task requires:
//! it answers "does deletion agree with dense evaluation" and is paired, in the same test, with the
//! hand-computed value that pins both to the mathematics.
//!
//! # Readings taken where the doc comment is silent
//!
//! 1. **Fewer than two observations.** `pearson`'s doc pins the zero-variance case and nothing
//!    else. The reading asserted here is `n == 0` (nothing to correlate at all) is
//!    `EmptyInput`, and `0 < n < 2` is `InsufficientSamples` — that variant is documented as
//!    "fewer observations than the statistic's degrees of freedom require", and a correlation
//!    needs two points before "how they co-vary" means anything. It is also the split the absorbed
//!    implementation made: `mrmr_utils.rs:92` refuses `n < 2` *before* it reaches the vanishing
//!    denominator at `:101`, so the zero-variance convention applies at `n >= 2` and not below.
//!    That precedence matters, because a single observation has zero variance and would otherwise
//!    fall into the `Ok((0, n))` convention.
//! 2. **The same split after pairwise deletion.** The count that decides is the count of surviving
//!    pairs, not the length of the input slices.
//! 3. **A non-finite input.** The doc is silent, and this suite deliberately does not force a
//!    choice between refusing it and propagating it. What it does pin is that a `NaN` must not be
//!    laundered into a plausible number: either a typed `NonFiniteInput`, or an `r` that is itself
//!    `NaN`. Returning the zero-variance sentinel for a `NaN` denominator — which is what a
//!    `if !(denominator > 0)` guard would do — is the defect this rules out.
//!
//! # Corner cases
//!
//! | Row | Class | Test |
//! |---|---|---|
//! | A | Empty input | `test_empty_input_is_empty_input_error`, `test_pairwise_complete_empty_is_empty_input` |
//! | B | Single element | `test_single_observation_is_insufficient_samples`, `test_pairwise_complete_with_one_surviving_pair_is_insufficient_samples` |
//! | C | Two quantities coincide | `test_perfect_positive_correlation_is_exactly_one` (y is an exact affine image of x), `test_zero_variance_returns_ok_zero_not_an_error` (a constant column: every value tied) |
//! | D | An index expression degenerates | `test_zero_variance_returns_ok_zero_not_an_error` — the denominator `sqrt(Sxx*Syy)` is the only compound expression here and this is where it collapses to zero; `test_single_observation_is_insufficient_samples` collapses the `n - 1` degrees of freedom |
//! | E | Documented threshold, both sides | `test_zero_variance_returns_ok_zero_not_an_error` (at the threshold: variance exactly zero) and `test_variance_just_above_zero_is_not_the_zero_sentinel` (just above it: a sample that differs in one place by `2^-10`) |
//! | F | Zero | `test_uncorrelated_sample_is_exactly_zero` — an `r` of exactly zero that is *not* the zero-variance sentinel, so the sentinel is never the only place zero is pinned |
//! | G | Negative | `test_hand_computed_r_with_negative_observations`, `test_perfect_negative_correlation_is_exactly_minus_one`, `test_hand_computed_r_on_a_small_sample` (the -0.8 half) |
//! | H | Exact domain boundary | `r` has no probability argument, so "exactly 0 or 1" reads as the ends of `r`'s own range: `test_perfect_positive_correlation_is_exactly_one` and `test_perfect_negative_correlation_is_exactly_minus_one` sit on `+1` and `-1`, and `test_r_is_bounded_by_one_over_a_generated_family` shows the interior never leaves them |
//! | I | Non-finite | `test_non_finite_observation_is_not_laundered` (NaN, +inf, -inf) |
//! | J | Overflow and underflow reach | `test_extreme_magnitudes_preserve_perfect_correlation` and `test_tiny_magnitudes_preserve_perfect_correlation`, each with a scale chosen per precision so that the *sums of squares* stay in range while their *product* does not |
//! | K | f32, f64, Float106 | every test below calls a generic helper three times, with a tolerance per precision |

