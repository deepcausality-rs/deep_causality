/// x = [1, 2, 3, 4], y = [1, 3, 2, 4] and its reflection y' = 5 - y = [4, 2, 3, 1].
///
/// Closed form, by hand:
///   x̄ = 10/4 = 2.5   dx  = [-1.5, -0.5,  0.5, 1.5]   Σdx²  = 2.25+0.25+0.25+2.25 = 5
///   ȳ = 10/4 = 2.5   dy  = [-1.5,  0.5, -0.5, 1.5]   Σdy²  = 2.25+0.25+0.25+2.25 = 5
///   Σdxdy = 2.25 - 0.25 - 0.25 + 2.25 = 4
///   r = 4 / √(5·5) = 4/5 = 0.8
///
/// Reflecting y about its mean negates every dy and therefore negates Σdxdy while leaving Σdy²
/// alone, so r' = -4/5 = -0.8.
fn check_hand_computed_small_sample<T>(tol: f64)
where
    T: RealField + FromPrimitive,
{
    let x = lift_array::<T>(&[1.0, 2.0, 3.0, 4.0]);
    let y = lift_array::<T>(&[1.0, 3.0, 2.0, 4.0]);
    let y_reflected = lift_array::<T>(&[4.0, 2.0, 3.0, 1.0]);

    let (r, n) = expect_ok(pearson(&x, &y), "hand-computed 0.8");
    // 0.8: 4/5 from the working above.
    assert_close(r, lift::<T>(0.8), tol, "r for x=[1,2,3,4], y=[1,3,2,4]");
    // 4: the number of pairs supplied.
    assert_eq!(n, 4, "the count is the number of pairs used");

    let (r_reflected, n_reflected) = expect_ok(pearson(&x, &y_reflected), "hand-computed -0.8");
    // -0.8: -4/5, the reflection argument above.
    assert_close(
        r_reflected,
        lift::<T>(-0.8),
        tol,
        "r for x=[1,2,3,4], y=[4,2,3,1]",
    );
    assert_eq!(n_reflected, 4, "the count is the number of pairs used");
}

