/// The missing-data policy, quoted from the doc comment:
///
/// > a pair contributes only when both entries are `Some`, and the returned count says how many
/// > did.
///
/// The fixture has six rows and four surviving pairs:
///
///   index | x        | y        | survives
///   ------|----------|----------|---------
///     0   | Some(1)  | Some(1)  | yes
///     1   | None     | Some(7)  | no  — x missing, so y's 7 is discarded with it
///     2   | Some(2)  | Some(3)  | yes
///     3   | Some(3)  | Some(2)  | yes
///     4   | Some(4)  | Some(4)  | yes
///     5   | Some(9)  | None     | no  — y missing, so x's 9 is discarded with it
///
/// The survivors are x = [1, 2, 3, 4] against y = [1, 3, 2, 4], the sample computed by hand in
/// `check_hand_computed_small_sample`: r = 4/5 = 0.8, over 4 pairs and not 6.
///
/// The two discarded partners (7 and 9) are far outside the surviving range on purpose. An
/// implementation that keeps a half-present row — by substituting zero, or by dropping only the
/// missing entry and letting the columns slip out of alignment — moves `r` by far more than the
/// tolerance, so the assertion detects it rather than merely tolerating it.
fn check_pairwise_drops_half_present_rows<T>(tol: f64)
where
    T: RealField + FromPrimitive,
{
    // Spelled out row by row, in the order of the table above.
    let col_x = lift_array::<T>(&[1.0, 0.0, 2.0, 3.0, 4.0, 9.0]);
    let col_y = lift_array::<T>(&[1.0, 7.0, 3.0, 2.0, 4.0, 0.0]);
    let x = [
        Some(col_x[0]),
        None,
        Some(col_x[2]),
        Some(col_x[3]),
        Some(col_x[4]),
        Some(col_x[5]),
    ];
    let y = [
        Some(col_y[0]),
        Some(col_y[1]),
        Some(col_y[2]),
        Some(col_y[3]),
        Some(col_y[4]),
        None,
    ];

    let (r, n) = expect_ok(pearson_pairwise_complete(&x, &y), "pairwise deletion");

    // 0.8: 4/5, the hand computation quoted above.
    assert_close(r, lift::<T>(0.8), tol, "r over the surviving pairs");
    // 4: the four rows where both columns are Some, out of six rows supplied.
    assert_eq!(
        n, 4,
        "the count is the number of surviving pairs, not the number of rows"
    );
}

