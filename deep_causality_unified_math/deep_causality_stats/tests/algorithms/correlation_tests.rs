/// Invariance under a positive affine map of either argument.
///
/// Replacing y by `a·y + b` with `a > 0` multiplies every dy by `a` and leaves the centring alone,
/// so Σdxdy scales by `a` and √Σdy² scales by `a`; the two cancel. The same holds for x. The
/// constants used are exact binary fractions (2.5, -7.5, 0.25, 100.0) so the transform introduces
/// no rounding of its own.
fn check_positive_affine_invariance<T>(tol: f64)
where
    T: RealField + FromPrimitive,
{
    let x = lift_array::<T>(&[1.0, 2.0, 3.0, 4.0]);
    let y = lift_array::<T>(&[1.0, 3.0, 2.0, 4.0]);

    let (base, n_base) = expect_ok(pearson(&x, &y), "affine base");

    let y_scaled = affine(&y, 2.5, -7.5);
    let (r_y, n_y) = expect_ok(pearson(&x, &y_scaled), "affine on y");
    assert_close(r_y, base, tol, "r is invariant under 2.5·y - 7.5");
    assert_eq!(n_y, n_base, "an affine map cannot change the count");

    let x_scaled = affine(&x, 0.25, 100.0);
    let (r_x, n_x) = expect_ok(pearson(&x_scaled, &y), "affine on x");
    assert_close(r_x, base, tol, "r is invariant under 0.25·x + 100");
    assert_eq!(n_x, n_base, "an affine map cannot change the count");
}

#[test]
