// -------------------------------------------------------------------------------------------
// Row J: reach at the type's own extremes.
//
// Both tests use x = [1, 2, 3, 4]·s and y = x + x, so the answer is the invariant r = 1 for every
// scale: `r` is invariant under a positive scaling of either argument, and doubling is exact in
// binary floating point, so no rounding enters the construction.
//
// The scales are chosen per precision from the type's own exponent range, so that the sums of
// squares stay representable while their *product* does not:
//
//   Σdx² = 5s²   and   Σdy² = 20s²   (dx = [-1.5, -0.5, 0.5, 1.5]·s), so their product is 100s⁴.
//
//   f32   (max 3.4e38, min normal 1.2e-38): s = 1e15  → 5s² = 5e30,   100s⁴ = 1e62  → +inf
//                                            s = 1e-15 → 5s² = 5e-30,  100s⁴ = 1e-58 → 0
//   f64   (max 1.8e308, min normal 2.2e-308): s = 1e100  → 5s² = 5e200,  100s⁴ = 1e402  → +inf
//                                              s = 1e-120 → 5s² = 5e-240, 100s⁴ = 1e-478 → 0
//   Float106 carries an f64 exponent, so it takes the f64 scales.
//
// An implementation that forms `Σdx²·Σdy²` before taking the root therefore divides by inf or by
// zero and cannot return 1; one that scales the deviations, or takes the two roots separately,
// stays in range. That is the vector_norm_l2 failure mode the corner-case table's row J names.
// -------------------------------------------------------------------------------------------

fn check_extreme_magnitudes<T>(scale: f64, tol: f64)
where
    T: RealField + FromPrimitive,
{
    let x = lift_array::<T>(&[scale, 2.0 * scale, 3.0 * scale, 4.0 * scale]);
    let y = doubled(&x);

    let (r, n) = expect_ok(pearson(&x, &y), "extreme magnitudes");

    // 1.0: y = 2x is a positive scaling of x, and r is invariant under one, so the perfect
    // correlation of the unscaled sample is preserved.
    assert_close(r, lift::<T>(1.0), tol, "r at an extreme scale");
    // 4: the number of pairs supplied.
    assert_eq!(n, 4, "the count is the number of pairs used");
}

#[test]
fn test_extreme_magnitudes_preserve_perfect_correlation() {
    check_extreme_magnitudes::<f32>(1e15, F32.native);
    check_extreme_magnitudes::<f64>(1e100, F64.native);
    check_extreme_magnitudes::<Float106>(1e100, F106.native);
}

#[test]
fn test_tiny_magnitudes_preserve_perfect_correlation() {
    check_extreme_magnitudes::<f32>(1e-15, F32.native);
    check_extreme_magnitudes::<f64>(1e-120, F64.native);
    check_extreme_magnitudes::<Float106>(1e-120, F106.native);
}

// -------------------------------------------------------------------------------------------
// Row J, one step further out: the centred sums themselves leave the type.
//
// The two tests above are scaled so that `Σdx²` and `Σdy²` stay representable and only their
// *product* does not. Past that there is a second band, where the sums of squares are the things
// that go: with dx = [-1.5, -0.5, 0.5, 1.5]·s,
//
//   f32   (max 3.4e38, min normal 1.2e-38): s = 1e30   → 2.25s²  = 2.3e60  → +inf
//                                            s = 1e-30  → 2.25s²  = 2.3e-60 → 0
//   f64   (max 1.8e308, min normal 2.2e-308): s = 1e200  → 2.25s² = 2.3e400 → +inf
//                                              s = 1e-200 → 2.25s² = 2.3e-400 → 0
//   Float106 carries an f64 exponent, so it takes the f64 scales.
//
// The answer is the same invariant `r = 1`: `r` is unchanged by a positive scaling of either
// sample, and the scale is the only thing that differs from the fixture used above. Two distinct
// wrong answers are on offer here and both are worse than an error: `Σdx² = +∞` divides `∞` by
// `∞` and returns `NaN`, and `Σdx² = 0` reaches the zero-variance exit and returns `Ok(0)` — the
// documented answer for a *constant* column — for a sample that is perfectly correlated.
// -------------------------------------------------------------------------------------------

#[test]
