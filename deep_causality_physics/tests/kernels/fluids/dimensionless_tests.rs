#[test]
fn test_peclet_equals_reynolds_times_prandtl() {
    // Pe = uL/α, Re = uL/ν, Pr = ν/α ⇒ Pe = Re·Pr, for any ν.
    for &(u, l, v, alpha) in &[
        (1.0f64, 0.01f64, 1.0e-6f64, 1.43e-7f64),
        (250.0, 60.0, 1.46e-5, 2.2e-5),
        (1e-3, 1e-3, 1.5e-5, 2.2e-5),
        (7800.0, 10.0, 1e-4, 1e-5),
        (1e5, 1e3, 1e-7, 1e-9),
    ] {
        let pe = peclet_number_kernel(&speed(u), &length(l), alpha).unwrap();
        let re = reynolds_number_kernel(&speed(u), &length(l), &nu(v)).unwrap();
        let pr = prandtl_number_kernel(&nu(v), alpha).unwrap();
        close(pe, re * pr, &format!("Pe = Re*Pr at u={u:e}, L={l:e}"));
    }
}

#[test]
fn test_rayleigh_equals_grashof_times_prandtl() {
    // Ra = gβΔT·L³/(να), Gr = gβΔT·L³/ν², Pr = ν/α ⇒ Ra = Gr·Pr.
    for &(g, beta, dt, l, v, alpha) in &[
        (9.80665f64, 3.4e-3f64, 10.0f64, 0.1f64, 1.5e-5f64, 2.2e-5f64),
        (9.80665, 2.07e-4, 20.0, 0.05, 1.0e-6, 1.43e-7),
        (1.62, 1e-3, 5.0, 2.0, 1e-4, 1e-5),
        (24.79, 1e-5, 1e3, 1e2, 1e-3, 1e-6),
    ] {
        let ra = rayleigh_number_kernel(g, beta, dt, &length(l), &nu(v), alpha).unwrap();
        let gr = grashof_number_kernel(g, beta, dt, &length(l), &nu(v)).unwrap();
        let pr = prandtl_number_kernel(&nu(v), alpha).unwrap();
        close(ra, gr * pr, &format!("Ra = Gr*Pr at L={l:e}, nu={v:e}"));
    }
}

#[test]
fn test_lewis_equals_schmidt_over_prandtl() {
    // Le = α/D, Sc = ν/D, Pr = ν/α ⇒ Le = Sc/Pr.
    for &(v, alpha, dm) in &[
        (1.5e-5f64, 2.2e-5f64, 2.0e-5f64),
        (1.0e-6, 1.43e-7, 1.5e-9),
        (9.0e-4, 8.6e-8, 1e-10),
        (1e-3, 1e-3, 1e-3),
    ] {
        let le = lewis_number_kernel(alpha, dm).unwrap();
        let sc = schmidt_number_kernel(&nu(v), dm).unwrap();
        let pr = prandtl_number_kernel(&nu(v), alpha).unwrap();
        close(
            le,
            sc / pr,
            &format!("Le = Sc/Pr at nu={v:e}, alpha={alpha:e}"),
        );
    }
}

#[test]
fn test_mach_and_froude_are_one_at_their_own_reference_speed() {
    // Definitional fixed points: Ma = 1 exactly when u = a, and Fr = 1 exactly when u = sqrt(gL).
    // No oracle needed — the value is forced by the definition.
    for a in [1e-3f64, 1.0, 340.29, 1e6] {
        assert_eq!(mach_number_kernel(&speed(a), &speed(a)).unwrap(), 1.0);
    }
    for (g, l) in [(9.80665f64, 2.5f64), (1.62, 100.0), (24.79, 1e-3)] {
        let got = froude_number_kernel(&speed((g * l).sqrt()), g, &length(l)).unwrap();
        close(got, 1.0, &format!("Fr = 1 at u = sqrt(g*L), g={g}, L={l}"));
    }
}

#[test]
fn test_the_ratio_kernels_are_reciprocal_under_swapped_arguments() {
    // Pr, Sc and Le are each a ratio of two diffusivities, so swapping them inverts the result.
    // An invariant, independent of what either value is.
    for (a, b) in [(1.5e-5f64, 2.2e-5f64), (9.0e-4, 8.6e-8), (1e-9, 1e3)] {
        let fwd = prandtl_number_kernel(&nu(a), b).unwrap();
        let rev = prandtl_number_kernel(&nu(b), a).unwrap();
        close(
            fwd * rev,
            1.0,
            &format!("Pr(a,b)*Pr(b,a) = 1 at {a:e}, {b:e}"),
        );
        let lf = lewis_number_kernel(a, b).unwrap();
        let lr = lewis_number_kernel(b, a).unwrap();
        close(
            lf * lr,
            1.0,
            &format!("Le(a,b)*Le(b,a) = 1 at {a:e}, {b:e}"),
        );
    }
}

