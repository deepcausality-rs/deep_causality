//! The eighteen dimensionless-number kernels, against independent oracles.
//!
//! # What changed, and why
//!
//! The previous suite computed its own expectations by retyping each kernel's formula —
//! `let expected = 1000.0 * 9.8 * 1.0e-4 / 0.072;` beside a call to `bond_number_kernel` — which
//! asserts only that an expression was written the same way twice and passes against a kernel that
//! is wrong in the same way. It also tested one hand-chosen input per kernel.
//!
//! Both are replaced. The expected values in the tables below are generated by
//! `scripts/physics_oracles.py`, which evaluates the **textbook definitions** in 50-digit decimal —
//! a different language, a different source for the formula, and more precision than `f64` carries,
//! so the assertions measure the kernel's error against the mathematics rather than against a
//! second copy of itself. Definitions are cited in that script's header (White, *Fluid Mechanics*
//! 7th ed. Table 5.2; Bird, Stewart & Lightfoot, *Transport Phenomena* 2nd ed.; Chapman & Cowling).
//!
//! # Ranges, not points
//!
//! Each table spans many decades and several physical regimes — creeping flow to re-entry, microns
//! to kilometres, liquid metals at `Pr ≈ 0.003` to heavy oils at `Pr ≈ 1e4`, terrestrial, lunar and
//! Jovian gravity. A kernel that is right at one comfortable value and wrong at the extremes fails
//! here.
//!
//! # The identities are the strongest check
//!
//! `Pe = Re·Pr`, `Ra = Gr·Pr` and `Le = Sc/Pr` each relate three kernels that share no code. They
//! cannot be satisfied by a formula retyped consistently, and they catch an error in any one of the
//! three from the other two. The module under test names all three in its own documentation.

use deep_causality_physics::{
    Density, KinematicViscosity, Length, PhysicsErrorEnum, Speed, Viscosity, bond_number_kernel,
    capillary_number_kernel, eckert_number_kernel, froude_number_kernel, grashof_number_kernel,
    knudsen_number_kernel, lewis_number_kernel, mach_number_kernel, nusselt_number_kernel,
    particle_stokes_number_kernel, peclet_number_kernel, prandtl_number_kernel,
    rayleigh_number_kernel, reynolds_number_kernel, richardson_number_kernel,
    schmidt_number_kernel, strouhal_number_kernel, weber_number_kernel,
};

/// Relative tolerance. The oracle is exact to 50 digits, so what is being measured is the kernel's
/// own `f64` rounding: a handful of operations, each half an ulp.
const REL: f64 = 1e-14;

/// Asserts `got` matches the oracle to `REL` *relatively*, which is the only scale-free way to
/// compare across tables spanning `1e-6` to `1e15`.
#[track_caller]
fn close(got: f64, want: f64, case: &str) {
    let scale = want.abs().max(1.0);
    assert!(
        (got - want).abs() <= REL * scale,
        "{case}: got {got:.17e}, oracle {want:.17e}, relative error {:.3e}",
        ((got - want) / scale).abs()
    );
}

fn speed(v: f64) -> Speed<f64> {
    Speed::new(v).unwrap()
}
fn length(v: f64) -> Length<f64> {
    Length::new(v).unwrap()
}
fn nu(v: f64) -> KinematicViscosity<f64> {
    KinematicViscosity::new(v).unwrap()
}
fn density(v: f64) -> Density<f64> {
    Density::new(v).unwrap()
}
fn viscosity(v: f64) -> Viscosity<f64> {
    Viscosity::new(v).unwrap()
}

