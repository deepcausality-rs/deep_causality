#[test]
fn test_weber_is_quadratic_in_speed_and_linear_in_length() {
    // We ∝ ρu²L/σ. Doubling u must quadruple it; doubling L must double it. Catches a squared
    // term written linear, which a single-point value test cannot see.
    let (rho, l, sigma) = (1000.0f64, 0.001f64, 0.072f64);
    for u in [1e-3f64, 0.5, 2.0, 100.0] {
        let base = weber_number_kernel(&density(rho), &speed(u), &length(l), sigma).unwrap();
        let doubled_u =
            weber_number_kernel(&density(rho), &speed(2.0 * u), &length(l), sigma).unwrap();
        let doubled_l =
            weber_number_kernel(&density(rho), &speed(u), &length(2.0 * l), sigma).unwrap();
        close(
            doubled_u,
            4.0 * base,
            &format!("We(2u) = 4We(u) at u={u:e}"),
        );
        close(
            doubled_l,
            2.0 * base,
            &format!("We(2L) = 2We(L) at u={u:e}"),
        );
    }
}

#[test]
fn test_grashof_is_cubic_in_length_and_rayleigh_likewise() {
    // Both carry L³. Doubling L multiplies them by eight.
    let (g, beta, dt, v, alpha) = (9.80665f64, 3.4e-3f64, 10.0f64, 1.5e-5f64, 2.2e-5f64);
    for l in [1e-3f64, 0.05, 1.0, 100.0] {
        let gr = grashof_number_kernel(g, beta, dt, &length(l), &nu(v)).unwrap();
        let gr2 = grashof_number_kernel(g, beta, dt, &length(2.0 * l), &nu(v)).unwrap();
        close(gr2, 8.0 * gr, &format!("Gr(2L) = 8Gr(L) at L={l:e}"));
        let ra = rayleigh_number_kernel(g, beta, dt, &length(l), &nu(v), alpha).unwrap();
        let ra2 = rayleigh_number_kernel(g, beta, dt, &length(2.0 * l), &nu(v), alpha).unwrap();
        close(ra2, 8.0 * ra, &format!("Ra(2L) = 8Ra(L) at L={l:e}"));
    }
}

#[test]
fn test_froude_is_inverse_square_root_in_gravity_and_length() {
    // Fr ∝ u/sqrt(gL): quadrupling g must halve it.
    for (u, g, l) in [
        (10.0f64, 9.80665f64, 2.5f64),
        (0.5, 1.62, 0.1),
        (1e3, 24.79, 1e6),
    ] {
        let base = froude_number_kernel(&speed(u), g, &length(l)).unwrap();
        let quad_g = froude_number_kernel(&speed(u), 4.0 * g, &length(l)).unwrap();
        let quad_l = froude_number_kernel(&speed(u), g, &length(4.0 * l)).unwrap();
        close(quad_g, 0.5 * base, &format!("Fr(4g) = Fr/2 at g={g}"));
        close(quad_l, 0.5 * base, &format!("Fr(4L) = Fr/2 at L={l:e}"));
    }
}

#[test]
fn test_richardson_is_inverse_square_in_speed() {
    // Ri ∝ 1/u². Doubling u must quarter it.
    for u in [1e-2f64, 1.0, 50.0] {
        let base =
            richardson_number_kernel(9.80665, 3.4e-3, 10.0, &length(1.0), &speed(u)).unwrap();
        let doubled =
            richardson_number_kernel(9.80665, 3.4e-3, 10.0, &length(1.0), &speed(2.0 * u)).unwrap();
        close(doubled, 0.25 * base, &format!("Ri(2u) = Ri/4 at u={u:e}"));
    }
}

