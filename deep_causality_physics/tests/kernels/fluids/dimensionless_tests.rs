#[test]
fn test_a_zero_numerator_gives_zero_rather_than_an_error() {
    // Every one of these is a well-posed zero: a fluid at rest has Re = Ma = We = 0. Only the
    // divisor may be refused, so these must succeed and return exactly zero.
    assert_eq!(
        reynolds_number_kernel(&speed(0.0), &length(1.0), &nu(1e-6)).unwrap(),
        0.0
    );
    assert_eq!(
        mach_number_kernel(&speed(0.0), &speed(340.29)).unwrap(),
        0.0
    );
    assert_eq!(
        weber_number_kernel(&density(1000.0), &speed(0.0), &length(1.0), 0.072).unwrap(),
        0.0
    );
    assert_eq!(
        froude_number_kernel(&speed(0.0), 9.80665, &length(1.0)).unwrap(),
        0.0
    );
    assert_eq!(knudsen_number_kernel(0.0, &length(1.0)).unwrap(), 0.0);
    assert_eq!(nusselt_number_kernel(0.0, &length(1.0), 0.6).unwrap(), 0.0);
    assert_eq!(
        eckert_number_kernel(&speed(0.0), 1004.0, 100.0).unwrap(),
        0.0
    );
}

#[test]
fn test_a_zero_length_is_a_value_where_it_is_a_numerator() {
    // L in the numerator: Re and Nu are zero at zero length. This is the mirror of the divisor
    // case below, and the two must not be conflated.
    assert_eq!(
        reynolds_number_kernel(&speed(1.0), &length(0.0), &nu(1e-6)).unwrap(),
        0.0
    );
    assert_eq!(nusselt_number_kernel(10.0, &length(0.0), 0.6).unwrap(), 0.0);
}

